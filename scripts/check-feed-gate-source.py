"""Verify the public source pin and an independently specified fail/control pair."""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/lab/feed-gate"
manifest = json.loads((SOURCE / "manifest.json").read_text())
assert manifest["commit"] == "f8c48256e12b96523807ba8f59c04b798517e04e"
for name, record in manifest["files"].items():
    assert hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() == record["sha256"], name
sys.path.insert(0, str(SOURCE))
sys.dont_write_bytecode = True  # public/ must contain source, never host-generated bytecode
from replay.admission import admit  # noqa: E402

try:
    admit((SOURCE / "bad-clock.jsonl").read_bytes())
except ValueError as exc:
    assert str(exc) == "receipt/availability must be nondecreasing and received <= available"
else:
    raise AssertionError("The broken timestamp must be refused")
header, rows, report = admit((SOURCE / "correct.jsonl").read_bytes())
assert header["data_kind"] == "synthetic"
assert [r["status"] for r in rows] == ["AVAILABLE", "AVAILABLE"]
assert [r["bid_size"] for r in rows] == [300, 100]  # replacement, not addition
assert [r["available_ms"] for r in rows] == [12, 22]
assert rows[1]["bid_tick"] == 4900 and rows[1]["ask_tick"] == 5100
assert report["records"] == 2
assert report["source_sha256"] == hashlib.sha256((SOURCE / "correct.jsonl").read_bytes()).hexdigest()
print("PASS: source pins; actual Python rejects bad clock; corrected control yields exact expected book")
